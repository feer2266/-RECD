def write(name, doc, body):
    with open(os.path.join(OUT, name + ".lua"), "w") as f:
        f.write(HEADER + f"-- {doc}\n\n" + body)


tiers = {t[0]: {"Id": t[0], "Name": t[1], "Index": i + 1, "Multiplier": t[2], "Color": t[3]}
         for i, t in enumerate(D.QUALITY_TIERS)}
qcats = {c: True for c in sorted(D.QUALITY_CATEGORIES)}

write("QualityTiers", "ASE vanilla item quality tiers (no Transcendent).", f"""local QualityTiers = {{}}

QualityTiers.Order = {lua([t[0] for t in D.QUALITY_TIERS])}

QualityTiers.Tiers = {lua(tiers)}

-- Categories whose items roll quality. Structures never do.
QualityTiers.Categories = {lua(qcats)}

-- Building progression is separate from item quality. Greenhouse is a special set.
QualityTiers.BuildingTiers = {lua(D.BUILDING_TIERS)}

function QualityTiers.Get(id)
	return QualityTiers.Tiers[id] or QualityTiers.Tiers.PRIMITIVE
end

-- Returns the highest tier whose multiplier threshold is <= rolled multiplier.
function QualityTiers.FromMultiplier(mult)
	local best = QualityTiers.Tiers.PRIMITIVE
	for _, id in ipairs(QualityTiers.Order) do
		local t = QualityTiers.Tiers[id]
		if mult >= t.Multiplier then
			best = t
		end
	end
	return best
end

-- Scale a base stat (damage, durability, armor) by quality.
function QualityTiers.ScaleStat(base, id)
	return base * QualityTiers.Get(id).Multiplier
end

return QualityTiers
""")

write("HarvestNodeDatabase", "The Island resource nodes and corpse sources (Weight = relative yield share).",
      f"""local HarvestNodeDatabase = {{}}

HarvestNodeDatabase.Nodes = {lua(nodes)}

-- Corpse sources use the creature's own model from CreatureLibrary.
-- Creature "*Tag" rows are generic fallbacks by body type.
HarvestNodeDatabase.Corpses = {lua(corpses)}

function HarvestNodeDatabase.RollDrop(nodeId, rng)
	local node = HarvestNodeDatabase.Nodes[nodeId] or HarvestNodeDatabase.Corpses[nodeId]
	if not node then
		return nil
	end
	rng = rng or Random.new()
	local total = 0
	for _, d in ipairs(node.Drops) do
		total += d.Weight
	end
	local pick = rng:NextNumber() * total
	for _, d in ipairs(node.Drops) do
		pick -= d.Weight
		if pick <= 0 then
			return d.Item
		end
	end
	return node.Drops[#node.Drops].Item
end

return HarvestNodeDatabase
""")

write("StructureDatabase", "Placeable structures (crafting, storage, farming, electrical, defense, beds) and building pieces.",
      f"""local StructureDatabase = {{}}

-- Slots/Fuel follow the ASE wiki; Slots = nil means not a container.
StructureDatabase.Structures = {lua(structures)}

-- Building pieces per tier. Models already exist (keep); these are data only.
-- Reinforced doors/gates/windows are Stone tier even though they look wooden.
StructureDatabase.BuildingPieces = {lua(building)}

function StructureDatabase.Get(id)
	return StructureDatabase.Structures[id] or StructureDatabase.BuildingPieces[id]
end

function StructureDatabase.ByCategory(category)
	local out = {{}}
	for _, s in pairs(StructureDatabase.Structures) do
		if s.Category == category then
			table.insert(out, s)
		end
	end
	return out
end

return StructureDatabase
""")

write("ItemDatabase_Island", "Inventory items: resources, tools, weapons, ammo, armor, shields, saddles.",
      f"""local QualityTiers = require(script.Parent.QualityTiers)

local ItemDatabase = {{}}

-- One entry per item. Quality is an instance property, never a separate model:
-- {{ Id = "MetalPick", Quality = "MASTERCRAFT", Multiplier = 7.3 }}
ItemDatabase.Items = {lua(items)}

function ItemDatabase.Get(id)
	return ItemDatabase.Items[id]
end

-- Build an item instance. Items without QualityEnabled always get PRIMITIVE.
function ItemDatabase.NewInstance(id, qualityId, multiplier)
	local def = ItemDatabase.Items[id]
	assert(def, "unknown item " .. tostring(id))
	local tier = def.QualityEnabled and QualityTiers.Get(qualityId) or QualityTiers.Tiers.PRIMITIVE
	return {{
		Id = id,
		Quality = tier.Id,
		Multiplier = def.QualityEnabled and (multiplier or tier.Multiplier) or 1,
	}}
end

function ItemDatabase.ByCategory(category)
	local out = {{}}
	for _, it in pairs(ItemDatabase.Items) do
		if it.Category == category then
			table.insert(out, it)
		end
	end
	return out
end

return ItemDatabase
""")

