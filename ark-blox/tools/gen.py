def lua(v, ind=0):
    pad = "\t" * ind
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)):
        if not v:
            return "{}"
        if all(not isinstance(x, (dict, list, tuple)) for x in v):
            return "{ " + ", ".join(lua(x) for x in v) + " }"
        return "{\n" + "".join(f"{pad}\t{lua(x, ind + 1)},\n" for x in v) + pad + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        parts = []
        for k, x in v.items():
            key = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else f"[{lua(k)}]"
            parts.append(f"{pad}\t{key} = {lua(x, ind + 1)},\n")
        return "{\n" + "".join(parts) + pad + "}"
    raise TypeError(v)


def pascal(name):
    return re.sub(r"[^A-Za-z0-9]", "", name.title().replace("-", " ")) if " " in name or "-" in name else name


manifest = []  # (assetPath, displayName, category, status, sketchfabQuery, note)


def add_model(path, name, cat, status, query="", note=""):
    manifest.append((path, name, cat, status, query, note))


# --------------------------------------------------------------- items
items = {}


def q(key, name):
    return D.MODEL_QUERIES.get(key, f"{name} realistic")


def add_item(iid, name, cat, sub, station=None, sources="Engram", model=None, status="todo", query=None, **extra):
    quality = cat in D.QUALITY_CATEGORIES and not (cat == "Tool" and iid in D.NO_QUALITY_TOOLS)
    entry = {
        "Id": iid,
        "DisplayName": name,
        "Category": cat,
        "SubCategory": sub,
        "CraftingStation": station,
        "Sources": sources.split(","),
        "QualityEnabled": quality,
        "Model": model,
    }
    entry.update(extra)
    items[iid] = entry
    add_model(model, name, cat, status, query if query is not None else q(iid, name), "")


for iid, name, sub in D.RESOURCES:
    st = "done" if iid in D.RESOURCE_MODELS_DONE else "todo"
    add_item(iid, name, "Resource", sub, None, "Harvest", f"ITEMS/Resources/{iid}", st,
             q(iid, name))

for iid, name, sub, station, src in D.TOOLS:
    add_item(iid, name, "Tool", sub, station, src, f"TOOLS/{iid}", query=q(iid, name))

for iid, name, sub, station, src, ammo in D.WEAPONS:
    add_item(iid, name, "Weapon", sub, station, src, f"WEAPONS/{iid}", query=q(iid, name), Ammo=ammo)

for iid, name, station in D.AMMO:
    add_item(iid, name, "Ammo", "Projectile", station, "Engram", f"AMMO/{iid}", query=q(iid, name))

for set_name, (pieces, station) in D.ARMOR_SETS.items():
    slots = D.SCUBA_SLOTS if set_name == "SCUBA" else D.ARMOR_SLOTS
    for piece, slot in zip(pieces, slots):
        iid = "Armor_" + re.sub(r"[^A-Za-z0-9]", "", piece)
        add_item(iid, piece, "Armor", set_name, station, D.LOOT if set_name != "Tek" else "Tekgram",
                 f"ARMOR/{set_name}/{re.sub(r'[^A-Za-z0-9]', '', piece)}",
                 query=D.SCUBA_QUERY[piece] if set_name == "SCUBA" else
                 f"{D.ARMOR_QUERY_SET[set_name]} {D.ARMOR_QUERY_SLOT[slot]}|{D.ARMOR_QUERY_SLOT[slot]} realistic", Slot=slot, ArmorSet=set_name)

for iid, name, station in D.SHIELDS:
    add_item(iid, name, "Shield", "Shield", station, D.LOOT if iid != "TekShield" else "Tekgram",
             f"SHIELDS/{iid}", query=q(iid, name))

for creature, stype in D.SADDLES:
    suffix = {"Platform": "PlatformSaddle", "Tek": "TekSaddle"}.get(stype, "Saddle")
    iid = f"{creature}{suffix}"
    label = {"Platform": "Platform Saddle", "Tek": "Tek Saddle"}.get(stype, "Saddle")
    st = "done" if (creature, stype) in D.SADDLE_MODELS_DONE else "todo"
    add_item(iid, f"{creature} {label}", "Saddle", stype, D.SADDLE_STATION[stype],
             D.LOOT if stype != "Tek" else "Tekgram", f"SADDLES/{iid}", st,
             D.SADDLE_QUERY[stype].format(c=creature),
             Creature=creature)

# --------------------------------------------------------------- structures
def pipe_query(sid, name):
    if "IrrigationPipe" not in sid:
        return None
    mat, kind = sid.split("IrrigationPipe")
    return f"{mat.lower()} {D.PIPE_QUERIES[kind]}|{D.PIPE_QUERIES[kind]}"


structures = {}
for sid, name, cat, fn, slots, fuel, status in D.STRUCTURES:
    folder = {"Crafting": "CRAFTING", "Storage": "STORAGE", "Farming": "FARMING", "Electrical": "ELECTRICAL",
              "Defense": "DEFENSE", "Bed": "BEDS", "Decor": "DECOR", "Utility": "CRAFTING"}[cat]
    structures[sid] = {
        "Id": sid, "DisplayName": name, "Category": cat, "Function": fn,
        "Slots": slots, "Fuel": fuel.split(",") if fuel else None,
        "QualityEnabled": False, "Model": f"{folder}/{sid}",
    }
    add_model(f"{folder}/{sid}", name, "Structure:" + cat, status, pipe_query(sid, name) or q(sid, name),
              "made in previous session" if status == "done" else "")

for sid, name in D.TEK_FUNCTIONAL:
    structures[sid] = {"Id": sid, "DisplayName": name, "Category": "Tek", "Function": "Tek utility",
                       "Slots": None, "Fuel": ["Element"], "QualityEnabled": False, "Model": f"TEK/{sid}"}
    add_model(f"TEK/{sid}", name, "Structure:Tek", "todo", q(sid, name))

